#!/usr/bin/env node
// Generates docs/COMMANDS.md from every command's slash-command definition, plus its
// required permission, rate-limit tier and image. `bun run docs:commands` rewrites the
// file; tests/docs/commands-doc.test.js fails when it is out of date.
const fs = require('node:fs');
const path = require('node:path');
const { PermissionFlagsBits, ApplicationCommandOptionType: T } = require('discord.js');

process.env.DISCORD_TOKEN ||= 'docs';
process.env.CLIENT_ID ||= 'docs';
process.env.LOG_LEVEL ||= 'silent';

const { RESTRICTED_COMMANDS } = require('../utils/permissions');
const { COMMAND_CATEGORIES, COOLDOWNS } = require('../utils/ratelimit');

const COMMANDS_DIR = path.join(__dirname, '..', 'commands');
const OUT = path.join(__dirname, '..', 'docs', 'COMMANDS.md');
const TYPE = { [T.String]: 'text', [T.Integer]: 'integer', [T.Number]: 'number', [T.Boolean]: 'true/false', [T.User]: 'user', [T.Channel]: 'channel', [T.Role]: 'role', [T.Attachment]: 'file' };
const PERMISSION = { [PermissionFlagsBits.Administrator]: 'Administrator', [PermissionFlagsBits.ManageGuild]: 'Manage Server' };

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

function optionRow(o) {
    const limits = [];
    if (o.choices?.length) limits.push(`one of: ${o.choices.map((c) => `\`${c.value}\``).join(', ')}`);
    if (o.min_value !== undefined || o.max_value !== undefined) limits.push(`${o.min_value ?? '…'} to ${o.max_value ?? '…'}`);
    if (o.max_length !== undefined) limits.push(`max ${o.max_length} chars`);
    return `| \`${o.name}\` | ${TYPE[o.type] ?? o.type} | ${o.required ? 'yes' : ''} | ${cell(o.description)} | ${cell(limits.join('; '))} |`;
}

function optionsTable(options) {
    if (!options?.length) return ['No options.'];
    return ['| Option | Type | Required | Description | Allowed |', '|---|---|---|---|---|', ...options.map(optionRow)];
}

function render() {
    const commands = fs.readdirSync(COMMANDS_DIR).filter((f) => f.endsWith('.js')).sort()
        .map((f) => require(path.join(COMMANDS_DIR, f)))
        .sort((a, b) => a.data.name.localeCompare(b.data.name));

    const lines = [
        '# Command reference',
        '',
        '<!-- Generated by scripts/gen-commands-doc.js (bun run docs:commands). Do not edit by hand. -->',
        '',
        `${commands.length} slash commands. **Image** \`full\` means the command needs a CLI tool that only the full Docker image (\`BOT_TARGET=full\`) ships; elsewhere it is hidden unless the tool is installed. **Cooldown** is per user: ${Object.entries(COOLDOWNS).map(([k, v]) => `${k} ${v / 1000}s`).join(', ')}; every command also counts toward \`RATE_LIMIT_DAILY\`. **Permission** can also be granted with \`OSINT_ALLOWED_ROLES\`.`,
        '',
        '| Command | Description | Permission | Cooldown | Image |',
        '|---|---|---|---|---|'
    ];
    for (const cmd of commands) {
        const { name, description } = cmd.data.toJSON();
        const perm = PERMISSION[RESTRICTED_COMMANDS[name]] ?? 'everyone';
        lines.push(`| [\`/${name}\`](#${name}) | ${cell(description)} | ${perm} | ${COMMAND_CATEGORIES[name] ?? 'light'} | ${cmd.requiresTool ? 'full' : 'any'} |`);
    }

    for (const cmd of commands) {
        const json = cmd.data.toJSON();
        lines.push('', `## ${json.name}`, '', cell(json.description), '');
        const subcommands = (json.options ?? []).filter((o) => o.type === T.Subcommand);
        if (subcommands.length) {
            for (const sub of subcommands) {
                lines.push(`### \`/${json.name} ${sub.name}\``, '', cell(sub.description), '', ...optionsTable(sub.options), '');
            }
        } else {
            lines.push(...optionsTable(json.options), '');
        }
    }
    return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

module.exports = { render, OUT };

if (require.main === module) {
    fs.writeFileSync(OUT, render());
    console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
    for (const cmd of fs.readdirSync(COMMANDS_DIR)) require(path.join(COMMANDS_DIR, cmd)).shutdown?.();
    process.exit(0);
}
